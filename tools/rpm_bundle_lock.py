#!/usr/bin/env python3
"""Pin explicitly selected vendor RPMs for rpm_sdk, without a rootfs solve."""

import argparse
import json
from pathlib import Path
import re
from urllib.parse import urljoin, urlparse

from relock import sha256_file, sync_repo
from rpmvercmp import compare_evr
from solve import parse_primary


def select_packages(records, names, architecture, base):
    """Select the newest requested package, respecting the target CPU."""
    selected = []
    for name in sorted(set(names)):
        candidates = [p for p in records if p["name"] == name and
                      p["arch"] in (architecture, "noarch")]
        if not candidates:
            raise ValueError("no {} or noarch package named {}".format(architecture, name))
        best = candidates[0]
        for candidate in candidates[1:]:
            left = tuple(candidate.get(k) for k in ("epoch", "version", "release"))
            right = tuple(best.get(k) for k in ("epoch", "version", "release"))
            comparison = compare_evr(left, right)
            if comparison > 0 or (comparison == 0 and candidate["arch"] == architecture):
                best = candidate
        checksum = best.get("checksum", "") or ""
        if best.get("checksum_type") != "sha256" or not re.fullmatch(r"[0-9a-fA-F]{64}", checksum):
            raise ValueError("{} does not have a SHA-256 package checksum".format(name))
        url = urljoin(base.rstrip("/") + "/", best["location"])
        if urlparse(url).scheme != "https" or urlparse(url).netloc != urlparse(base).netloc:
            raise ValueError("package URL must stay on the HTTPS repository host: {}".format(url))
        selected.append({
            "name": name, "architecture": best["arch"],
            "epoch": best.get("epoch"), "version": best["version"],
            "release": best["release"], "url": url, "sha256": checksum.lower(),
            "requires": best.get("requires", []),
        })
    return selected


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", required=True, help="HTTPS directory containing repodata/")
    parser.add_argument("--architecture", choices=["aarch64", "x86_64"], required=True)
    parser.add_argument("--package", action="append", default=[])
    parser.add_argument("--list", action="store_true", help="list available package names")
    parser.add_argument("--primary", help="use previously downloaded primary.xml[.gz/.zst]")
    parser.add_argument("--repo-cache", default=".buckos/rpm-bundle-repodata")
    parser.add_argument("--output", help="generated Starlark file defining PACKAGES")
    args = parser.parse_args(argv)
    if urlparse(args.repository).scheme != "https":
        parser.error("--repository must use HTTPS")
    if not args.list and (not args.package or not args.output):
        parser.error("pass --list or both --package and --output")
    primary = args.primary or sync_repo(args.repository.rstrip("/"), args.repo_cache, "vendor")
    records = list(parse_primary(str(primary)))
    if args.list:
        for name in sorted({p["name"] for p in records if p["arch"] in (args.architecture, "noarch")}):
            print(name)
        return
    try:
        packages = select_packages(records, args.package, args.architecture, args.repository)
    except ValueError as error:
        parser.error(str(error))
    # JSON string escaping is also valid in Starlark; emit only string/list
    # fields here, because JSON null is not valid Starlark.
    pins = [{k: p[k] for k in ("name", "url", "sha256", "requires")} for p in packages]
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        "# @generated by tools/rpm_bundle_lock.py; explicit selection, no dependency solve.\n"
        "PACKAGES = " + json.dumps(pins, indent=4, sort_keys=True) + "\n"
    )
    output.with_suffix(".lock.json").write_text(json.dumps({
        "schema": "buckos.rpm-bundle-lock.v1", "repository": args.repository,
        "architecture": args.architecture, "packages": packages,
        "dependency_resolution": "explicit-selection",
        "primary_sha256": sha256_file(primary),
    }, indent=2, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
